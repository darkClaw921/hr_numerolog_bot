"""
Модуль комбинаций секторов матрицы.

Содержит правила вида «если в нескольких секторах такие-то коэффициенты,
то выдаём такой-то текст». Каждое правило описывается компактным паттерном,
который разбирается небольшим парсером (DSL), и текстом интерпретации.

Раздел «Трансформации» здесь НЕ реализуется (по требованию — отложен).

Нотация паттернов
-----------------
Паттерн — это условия по секторам, разделённые ``+`` (иногда в исходнике
встречается ``=`` — трактуется так же).

* ``111`` — в секторе 1 ровно 3 единицы (количество цифр).
* ``4/44/444`` — в секторе 4 одна, две или три четвёрки (количество ∈ {1,2,3}).
* ``8/пуст`` — в секторе 8 ноль или одна восьмёрка (количество ∈ {0,1}).
* ``2222 и более`` — количество ≥ 4.
* ``семья 4/5/6`` — коэффициент сектора СЕМЬЯ (2/5/8) равен 4, 5 или 6.
* ``быт``/``темперамент``/``цель``/``стабильность``/``целеустремленность`` —
  производные коэффициенты (см. ``DERIVED_KEYS``); значения — обычные числа.
* ``логика``/``труд``/``долг`` и т.п. — уточнение реального сектора матрицы,
  значения трактуются как количество цифр (как у обычных токенов).
* ``ЧС 4/6`` — Число Судьбы ∈ {4,6}.
* ``5(пуст)`` — в секторе 5 ноль пятёрок.
"""

import re
from typing import Dict, List, Optional, Set, Tuple


# Производные коэффициенты (значения — обычные числа, а не количество цифр)
DERIVED_KEYS = {
    "семья": "sector_family",
    "быт": "sector_life",
    "темперамент": "sector_temperament",
    "цель": "sector_purpose",
    "целеустремленность": "sector_purpose",
    "целеустремлённость": "sector_purpose",
    "стабильность": "sector_purpose",
}

# Реальные секторы матрицы (значения — количество цифр)
REAL_SECTORS = {
    "характер": 1,
    "энергия": 2,
    "интерес": 3,
    "здоровье": 4,
    "логика": 5,
    "труд": 6,
    "удача": 7,
    "долг": 8,
    "память": 9,
}

EMPTY_WORDS = {"пуст", "пусто", "пустой", "пустая", "пустое", "-"}

MAX_COUNT = 9   # верхняя граница количества цифр в секторе для «и более»
MAX_COEF = 19   # верхняя граница производного коэффициента для «и более»


class SkipRule(Exception):
    """Сигнал, что правило не вычислимо (например, требует «среды») и пропускается."""


def _has_more(text: str) -> bool:
    return ("более" in text) or ("больше" in text)


def _strip_more(text: str) -> str:
    return text.replace("и более", "").replace("и больше", "").strip()


def _parse_digitrep(token: str) -> Tuple[Optional[int], Set[int]]:
    """Парсит токен-повтор цифры, возвращает (цифра, множество допустимых количеств)."""
    more = _has_more(token) or token.strip().endswith("+")
    token = _strip_more(token).replace("+", " ").strip()

    digit: Optional[int] = None
    counts: Set[int] = set()

    for sub in token.split("/"):
        sub = sub.strip().lower()
        if not sub:
            continue
        has_empty = (sub in EMPTY_WORDS) or ("пуст" in sub)
        chars = [c for c in sub if c.isdigit()]
        if chars:
            digit = int(chars[0])
        if has_empty:
            counts.add(0)
        elif chars:
            counts.add(len(chars))

    if more and counts:
        counts |= set(range(min(counts), MAX_COUNT + 1))

    return digit, counts


def _parse_plainint(token: str) -> Set[int]:
    """Парсит токен с обычными числами (производные коэффициенты, ЧС)."""
    more = _has_more(token)
    token = _strip_more(token)

    vals: Set[int] = set()
    for sub in token.split("/"):
        sub = sub.strip().lower()
        if not sub:
            continue
        if (sub in EMPTY_WORDS) or ("пуст" in sub):
            vals.add(0)
            continue
        m = re.search(r"\d+", sub)
        if m:
            vals.add(int(m.group()))

    if more and vals:
        vals |= set(range(max(vals), MAX_COEF + 1))

    return vals


# Тип условия: ("sector", digit, counts) | ("coef", key, vals) | ("destiny", vals)
Condition = Tuple


def _parse_part(part: str) -> List[Condition]:
    """Разбирает одну часть паттерна (между ``+``) в список условий."""
    part = part.strip()
    if not part:
        return []

    if "сред" in part.lower():  # «среда» — не вычислимо
        raise SkipRule()

    conditions: List[Condition] = []

    # Выделяем скобочные уточнения
    parens = re.findall(r"\(([^)]*)\)", part)
    main = re.sub(r"\([^)]*\)", "", part).strip()
    relabel: Optional[Tuple[str, object]] = None

    for p in parens:
        pl = p.strip().lower()
        if pl in EMPTY_WORDS or pl == "пуст":
            relabel = ("empty", None)
        elif pl in DERIVED_KEYS:
            relabel = ("derived", DERIVED_KEYS[pl])
        elif pl in REAL_SECTORS:
            relabel = ("real", REAL_SECTORS[pl])
        else:
            conditions.extend(_parse_part(p))  # независимое условие, напр. «ЧС 4/6»

    words = main.split()
    kw = words[0].lower() if words else ""
    rest = main[len(words[0]):] if words else ""

    if kw in ("чс", "ч.с."):
        conditions.append(("destiny", _parse_plainint(rest)))
        return conditions

    if kw in DERIVED_KEYS:
        conditions.append(("coef", DERIVED_KEYS[kw], _parse_plainint(rest)))
        return conditions

    if kw in REAL_SECTORS:
        _, counts = _parse_digitrep(rest)
        conditions.append(("sector", REAL_SECTORS[kw], counts))
        return conditions

    if relabel is not None:
        kind, ref = relabel
        if kind == "derived":
            conditions.append(("coef", ref, _parse_plainint(main)))
            return conditions
        if kind == "real":
            _, counts = _parse_digitrep(main)
            conditions.append(("sector", ref, counts))
            return conditions
        if kind == "empty":
            d, _ = _parse_digitrep(main)
            if d is not None:
                conditions.append(("sector", d, {0}))
            return conditions

    digit, counts = _parse_digitrep(main)
    if digit is not None:
        conditions.append(("sector", digit, counts))
    return conditions


def parse_pattern(pattern: str) -> List[Condition]:
    """Разбирает весь паттерн в список условий. Может бросить SkipRule."""
    pattern = pattern.replace("=", "+")
    conditions: List[Condition] = []
    for part in pattern.split("+"):
        conditions.extend(_parse_part(part))
    return conditions


def _actual_value(cond: Condition, results: Dict) -> int:
    kind = cond[0]
    if kind == "sector":
        return len(results["matrix"][cond[1]])
    if kind == "coef":
        return results[cond[1]]
    if kind == "destiny":
        return results["destiny_number"]
    return -1


def _matches(conditions: List[Condition], results: Dict) -> bool:
    for cond in conditions:
        allowed = cond[-1]
        if _actual_value(cond, results) not in allowed:
            return False
    return True


