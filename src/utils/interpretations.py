def get_additional_qualities(results: dict) -> dict:
    """
    Получает все интерпретации дополнительных качеств для результатов расчетов.
    
    Args:
        results: Словарь с результатами расчетов из calculate_all()
        
    Returns:
        Словарь с интерпретациями дополнительных качеств
    """
    matrix = results["matrix"]
    
    # Подсчитываем коэффициенты секторов
    sector_life = results["sector_life"]  # Быт (4/5/6)
    sector_temperament = results["sector_temperament"]  # Темперамент (3/5/7)
    sector_family = results["sector_family"]  # Семья (2/5/8)
    sector_purpose = results["sector_purpose"]  # Цель (1/4/7)
    energy_count = len(matrix[2])
    character_count = len(matrix[1])
    duty_count = len(matrix[8])
    labor_count = len(matrix[6])
    luck_count = len(matrix[7])
    
    return {
        "life": get_life_interpretation(sector_life),
        "temperament": get_temperament_interpretation(sector_temperament),
        "family": get_family_interpretation(sector_family),
        "stability": get_stability_interpretation(sector_purpose),
        "purpose": get_purpose_interpretation(sector_purpose, energy_count),
        "transformation": get_transformation_interpretation(character_count, duty_count, labor_count, luck_count),
        "destiny_number": get_destiny_number_interpretation(results["destiny_number"])
    }
